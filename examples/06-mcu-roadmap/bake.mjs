// Bake the roads around Shibuya station into C source for the MCU map:
//   data/baked/06-mcu-roadmap/roads_data.c   const arrays, one road per line
// Units are 0.5 m on a local grid centred on the station (x east, y south,
// x scaled by cos(latitude)), so everything fits int16 and the renderer
// never needs floating point.
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { execFileSync, spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { source } from '../../tools/sources.ts';
import { clipPolyline } from '../../tools/geo.ts';

const OUT = 'data/baked/06-mcu-roadmap';
const pbf = source('osm-tokyo23');
const roadsPbf = 'data/raw/tokyo23-highways.osm.pbf';
if (!existsSync(roadsPbf)) execFileSync('osmium', ['tags-filter', '-o', roadsPbf, pbf, 'w/highway'], { stdio: 'inherit' });

const [LON0, LAT0] = [139.7016, 35.6580];     // Shibuya station
const R = 5000;                                // half-size of the area: 2.5 km
const CLIP = 6250;                             // roads are cut 25% outside it
const M_PER_DEG = 111320;
const k = Math.cos((LAT0 * Math.PI) / 180);
const unit = ([lon, lat]) => [(lon - LON0) * k * M_PER_DEG * 2, (LAT0 - lat) * M_PER_DEG * 2];

const CLASS = {
  motorway: 0, trunk: 0, motorway_link: 0, trunk_link: 0,
  primary: 1, primary_link: 1,
  secondary: 2, secondary_link: 2, tertiary: 2, tertiary_link: 2,
  residential: 3, unclassified: 3, living_street: 3, service: 3, road: 3,
};

const byClass = [[], [], [], [], []];
const exp = spawn('osmium', ['export', '-f', 'geojsonseq', '--geometry-types=linestring', roadsPbf], { stdio: ['ignore', 'pipe', 'inherit'] });
for await (const line of createInterface({ input: exp.stdout })) {
  const f = JSON.parse(line.replace(/^\x1e/, ''));
  // Cutting roads just outside the area keeps every coordinate small enough
  // for the renderer's int32 arithmetic (see mcumap.h).
  for (const piece of clipPolyline(f.geometry.coordinates.map(unit), [-CLIP, -CLIP, CLIP, CLIP])) {
    const pts = piece.map(([x, y]) => [Math.round(x), Math.round(y)]);
    if (pts.length < 2 || !pts.some(([x, y]) => Math.abs(x) <= R && Math.abs(y) <= R)) continue;
    byClass[CLASS[f.properties.highway] ?? 4].push(pts);
  }
}

// Minor classes first: major roads are painted over them.
const rows = [], pts = [];
for (let c = 4; c >= 0; c--) {
  for (const p of byClass[c]) {
    const xs = p.map((q) => q[0]), ys = p.map((q) => q[1]);
    rows.push(`  {${Math.min(...xs)}, ${Math.min(...ys)}, ${Math.max(...xs)}, ${Math.max(...ys)}, ${pts.length / 2}, ${p.length}, ${c}},`);
    for (const [x, y] of p) pts.push(x, y);
  }
}
const lines = [];
for (let i = 0; i < pts.length; i += 16) lines.push('  ' + pts.slice(i, i + 16).join(', ') + ',');
mkdirSync(OUT, { recursive: true });
writeFileSync(`${OUT}/roads_data.c`, `// Generated by examples/06-mcu-roadmap/bake.mjs from OpenStreetMap (ODbL).
// Roads within 2.5 km of Shibuya station, cut at 3.1 km, 0.5 m units. Do not edit.
#include "mcumap.h"

const int16_t mm_pts[] = {
${lines.join('\n')}
};

// min x, min y, max x, max y, first point, point count, class
const mm_road mm_roads[] = {
${rows.join('\n')}
};

const uint16_t mm_road_count = ${rows.length};
`);
console.log(`${rows.length} roads (${byClass.map((a) => a.length).join('/')} by class), ${pts.length / 2} points`);
